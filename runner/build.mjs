import { mkdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { runnerHeaders } from './config.mjs';
import { outputConfig } from './output.mjs';
const root = fileURLToPath(new URL('./', import.meta.url));
const cloud = process.argv.includes('--vercel');
const test = process.argv.includes('--test');
const production = cloud || process.env.VERCEL_ENV === 'production' || process.env.CQ_DEPLOYMENT === 'production';
const config = runnerHeaders(process.env.APP_ORIGIN, production);
const outputRoot = resolve(root, '.vercel/output');
if (cloud) rmSync(outputRoot, { recursive: true, force: true });
const output = test ? '/tmp/cqstudio-runner-dist' : cloud ? resolve(outputRoot, 'static') : resolve(root, 'dist');
mkdirSync(output, { recursive: true });
writeFileSync(resolve(output, 'index.html'), readFileSync(resolve(root, 'index.html'), 'utf8').replace('__APP_ORIGIN__', config.origin));
writeFileSync(resolve(output, 'robots.txt'), 'User-agent: *\nDisallow: /\n');
if (test) writeFileSync(resolve(output, 'vercel.smoke.json'), JSON.stringify({ headers: config.headers }, null, 2));
else if (cloud) writeFileSync(resolve(outputRoot, 'config.json'), JSON.stringify(outputConfig(config.headers), null, 2));
else writeFileSync(resolve(output, 'headers.json'), JSON.stringify({ headers: config.headers }, null, 2));
console.log('Built isolated runner with generated exact-origin headers and no network permission.');
